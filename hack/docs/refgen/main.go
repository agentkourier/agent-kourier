// Command refgen writes the generated reference pages of the documentation site: one page for each resource kind in
// api/v1alpha1, read from the Go types and their doc comments and kubebuilder markers, and one page for the Helm chart's
// values, read from charts/agent-kourier/values.yaml and its comments. Run it from the repository root, through
// `make docs-ref`; a test fails while the committed pages differ from what it writes.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/agentkourier/agent-kourier/api/v1alpha1"
)

// Where the sources are and where the pages go, relative to the repository root.
const (
	apiDir     = "api/v1alpha1"
	valuesFile = "charts/agent-kourier/values.yaml"
	outDir     = "docs/reference"
)

func main() {
	rootDir := flag.String("root", ".", "the repository root")
	flag.Parse()
	files, err := generate(*rootDir)
	if err != nil {
		fmt.Fprintln(os.Stderr, "refgen:", err)
		os.Exit(1)
	}
	for path, content := range files {
		if err := os.WriteFile(filepath.Join(*rootDir, path), content, 0o644); err != nil { //nolint:gosec // documentation pages are world-readable
			fmt.Fprintln(os.Stderr, "refgen:", err)
			os.Exit(1)
		}
	}
}

// generate returns the generated pages, by their path relative to rootDir.
func generate(rootDir string) (map[string][]byte, error) {
	pages, err := apiReference(filepath.Join(rootDir, apiDir), apiDir, v1alpha1.APIVersion)
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", apiDir, err)
	}
	files := make(map[string][]byte, len(pages)+1)
	for kind, page := range pages {
		files[filepath.Join(outDir, strings.ToLower(kind)+".md")] = []byte(page)
	}
	src, err := os.ReadFile(filepath.Join(rootDir, valuesFile)) //nolint:gosec // the chart's own values file under the root given
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", valuesFile, err)
	}
	values, err := valuesReference(src, valuesFile)
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", valuesFile, err)
	}
	files[filepath.Join(outDir, "helm-values.md")] = []byte(values)
	return files, nil
}

// The references a maintainer keeps in a comment and a reader of the site has no use for: a parenthetical whose
// every item, separated by commas or semicolons, is a spec section or decision ("spec 8.2", "spec section 7", "spec D15"), a decision
// ("D14"), a risk ("R1"), a work package ("WP-21", "WP-20c review"), a phase ("Phase 5") or "see <identifier>"; and a
// "; see <identifier>" clause. An identifier has a capital letter, as Go names of any length do ("ParsePromptTemplate",
// "TriggerThread.EffectiveMaxIdle"), so "(see below)" stays.
var (
	parenthetical = regexp.MustCompile(`\s*\(([^()]*)\)`)
	refItem       = regexp.MustCompile(`^(?:spec (?:section )?(?:[\d.]+|[DR]\d+[a-z]?)|D\d+[a-z]?|R\d+|WP-\d+[a-z0-9]*(?: [a-z]+)*|Phase \d+|see ` + identifier + `)$`)
	seeClause     = regexp.MustCompile(`[;,]\s*see ` + identifier + `(?:[.;,]|$)`)
)

const identifier = `(?:[A-Z]\w*|[a-z]+[A-Z]\w*)(?:\.[A-Za-z_]\w*)*`

// readerText removes the maintainer references from comment text, outside code spans.
func readerText(s string) string {
	parts := strings.Split(s, "`")
	for i := 0; i < len(parts); i += 2 { // even parts are outside code spans
		parts[i] = parenthetical.ReplaceAllStringFunc(parts[i], func(m string) string {
			inner := parenthetical.FindStringSubmatch(m)[1]
			for _, item := range strings.FieldsFunc(inner, func(r rune) bool { return r == ',' || r == ';' }) {
				if !refItem.MatchString(strings.TrimSpace(item)) {
					return m
				}
			}
			return ""
		})
		parts[i] = seeClause.ReplaceAllStringFunc(parts[i], func(m string) string {
			if end := m[len(m)-1]; end == '.' || end == ';' || end == ',' {
				return string(end)
			}
			return ""
		})
	}
	return strings.Join(parts, "`")
}

// escapeText makes comment text safe as Markdown: outside code spans it escapes the characters that would start HTML,
// an entity or emphasis. In a table cell it also escapes the pipe.
func escapeText(s string, cell bool) string {
	var b strings.Builder
	inCode := false
	for _, r := range s {
		if r == '`' {
			inCode = !inCode
			b.WriteRune(r)
			continue
		}
		if inCode { // a table splits no cell inside a code span
			b.WriteRune(r)
			continue
		}
		switch r {
		case '&':
			b.WriteString("&amp;")
		case '<':
			b.WriteString("&lt;")
		case '>':
			b.WriteString("&gt;")
		case '*':
			b.WriteString(`\*`)
		case '|':
			if cell {
				b.WriteString(`\|`)
			} else {
				b.WriteRune(r)
			}
		default:
			b.WriteRune(r)
		}
	}
	return b.String()
}

// generatedNote is the line every generated page ends with.
func generatedNote(from string) string {
	return "\n---\n\nGenerated by `hack/docs/refgen` from `" + from + "`. Do not edit this page; change the source and run `make docs-ref`.\n"
}

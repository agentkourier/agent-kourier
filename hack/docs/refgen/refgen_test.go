// TestValuesReferenceCoversEveryKey reads the real values.yaml as data and checks that each of its keys is in the page.
func TestValuesReferenceCoversEveryKey(t *testing.T) {
	path := filepath.Join(root, "charts/agent-kourier/values.yaml")
	src, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	page, err := valuesReference(src, "charts/agent-kourier/values.yaml")
	if err != nil {
		t.Fatalf("valuesReference: %v", err)
	}
	var values map[string]any
	if err := yaml.Unmarshal(src, &values); err != nil {
		t.Fatal(err)
	}
	var walk func(prefix string, m map[string]any)
	walk = func(prefix string, m map[string]any) {
		for k, v := range m {
			path := prefix + k
			if prefix == "" {
				if !strings.Contains(page, "\n## "+path+"\n") {
					t.Errorf("no section for %s", path)
				}
			} else if !strings.Contains(page, "`"+path+"`") && !strings.Contains(page, "`"+path+".") { // a block mapping is its keys' rows
				t.Errorf("no row for %s", path)
			}
			if sub, ok := v.(map[string]any); ok && len(sub) > 0 && !flowInSource(src, k) {
				walk(path+".", sub)
			}
		}
	}
	walk("", values)
}

// flowInSource reports whether key's value is written in flow style ({...}) on its own line in src, which the page
// shows as one value rather than key by key.
func flowInSource(src []byte, key string) bool {
	for line := range strings.SplitSeq(string(src), "\n") {
		if rest, ok := strings.CutPrefix(strings.TrimSpace(line), key+": "); ok && strings.HasPrefix(rest, "{") {
			return true
		}
	}
	return false
}

// TestCommittedReferenceIsCurrent fails when api/v1alpha1 or the chart's values changed and the pages under
// docs/reference were not generated again: run `make docs-ref`.
func TestCommittedReferenceIsCurrent(t *testing.T) {
	files, err := generate(root)
	if err != nil {
		t.Fatalf("generate: %v", err)
	}
	for path, want := range files {
		got, err := os.ReadFile(filepath.Join(root, path))
		if err != nil {
			t.Errorf("%s: %v (run make docs-ref)", path, err)
			continue
		}
		if string(got) != string(want) {
			t.Errorf("%s is out of date: run make docs-ref", path)
		}
	}
}

// notMetrics are agentkourier_ strings in the code that name no metric: the event type of Agent Kourier's Slack message
// metadata, and test-only prefixes.
var notMetrics = []string{"agentkourier_message", "agentkourier_test_", "agentkourier_broker_test_"}

// TestMetricsReferenceListsEveryMetric fails when the code declares a metric that docs/reference/metrics.md, which is
// written by hand, does not list.
func TestMetricsReferenceListsEveryMetric(t *testing.T) {
	page, err := os.ReadFile(filepath.Join(root, "docs/reference/metrics.md"))
	if err != nil {
		t.Fatal(err)
	}
	name := regexp.MustCompile(`"(agentkourier_[a-z_]+)"`)
	for _, dir := range []string{"internal", "cmd"} {
		err := filepath.WalkDir(filepath.Join(root, dir), func(path string, d fs.DirEntry, err error) error {
			if err != nil || d.IsDir() || !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
				return err
			}
			src, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			for _, m := range name.FindAllStringSubmatch(string(src), -1) {
				if !slices.Contains(notMetrics, m[1]) && !strings.Contains(string(page), "`"+m[1]+"`") {
					t.Errorf("%s declares %s, which docs/reference/metrics.md does not list", path, m[1])
				}
			}
			return nil
		})
		if err != nil {
			t.Fatal(err)
		}
	}
}

// TestReaderTextStripsMaintainerReferences: the source keeps its references to the spec, decisions, risks, work

// section returns the part of a page under the heading "## name", up to the next "## ".
func section(t *testing.T, page, name string) string {
	t.Helper()
	_, after, ok := strings.Cut(page, "\n## "+name+"\n")
	if !ok {
		t.Fatalf("no section %q in:\n%s", name, page)
	}
	body, _, _ := strings.Cut(after, "\n## ")
	return body
}


// TestAPIReferenceCoversEveryField checks the generated reference of the real API against the Go types by reflection,
// which reads the types differently from the generator: every JSON field of every struct a resource reaches has a row
// in that struct's section.
func TestAPIReferenceCoversEveryField(t *testing.T) {
	pages, err := apiReference(filepath.Join(root, "api/v1alpha1"), "api/v1alpha1", v1alpha1.APIVersion)
	if err != nil {
		t.Fatalf("apiReference: %v", err)
	}
	for kind, typ := range map[string]reflect.Type{
		"Binding":        reflect.TypeFor[v1alpha1.Binding](),
		"AgentBackend":   reflect.TypeFor[v1alpha1.AgentBackend](),
		"ChatConnection": reflect.TypeFor[v1alpha1.ChatConnection](),
	} {
		page, ok := pages[kind]
		if !ok {
			t.Fatalf("no page for %s", kind)
		}
		seen := map[reflect.Type]bool{}
		var walk func(reflect.Type)
		walk = func(rt reflect.Type) {
			for rt.Kind() == reflect.Pointer || rt.Kind() == reflect.Slice || rt.Kind() == reflect.Map {
				rt = rt.Elem()
			}
			if rt.Kind() != reflect.Struct || rt.PkgPath() != reflect.TypeFor[v1alpha1.Binding]().PkgPath() || seen[rt] {
				return
			}
			seen[rt] = true
			body := section(t, page, rt.Name())
			for f := range rt.Fields() {
				name, _, _ := strings.Cut(f.Tag.Get("json"), ",")
				if !f.IsExported() || name == "" || name == "-" {
					continue
				}
				if !strings.Contains(body, "| `"+name+"` |") {
					t.Errorf("%s: section %s has no row for %s", kind, rt.Name(), name)
				}
				walk(f.Type)
			}
		}
		walk(typ)
	}
}


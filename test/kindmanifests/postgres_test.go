package kindmanifests_test

import (
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"
	"testing"
)

// postgresStub is a kubectl that logs its arguments, and what it is given on standard input for each call that reads a manifest from
// it, and says that the Secrets exist when STUB_EXISTS is set.
const postgresStub = `#!/bin/sh
echo "$*" >> "$STUB_LOG/argv"
case "$*" in
  *"get secret"*"-o name"*) printf '%s' "$STUB_EXISTS" ;;
esac
case "$*" in
  *" -f -"*) { echo "== $*"; cat; } >> "$STUB_LOG/stdin" ;;
esac
`

// runDeployPostgres runs deploy_postgres against the stub and returns what kubectl was asked and what it read from standard input.
func runDeployPostgres(t *testing.T, exists string) (argv, stdin string) {
	t.Helper()
	bin, logs := t.TempDir(), t.TempDir()
	if err := os.WriteFile(filepath.Join(bin, "kubectl"), []byte(postgresStub), 0o700); err != nil {
		t.Fatal(err)
	}
	cmd := exec.CommandContext(t.Context(), "bash", "-c", `set -eu; . "$1"; HERE=$(dirname "$1"); K=(kubectl --context kind-courier-fast); deploy_postgres`, "bash", "../../hack/kind/lib.sh")
	cmd.Env = append(os.Environ(), "PATH="+bin+string(os.PathListSeparator)+os.Getenv("PATH"), "STUB_LOG="+logs, "STUB_EXISTS="+exists)
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("deploy_postgres: %v\n%s", err, out)
	}
	return readLog(t, logs, "argv"), readLog(t, logs, "stdin")
}

// TestDeployPostgresNeverPutsThePasswordOnAnArgumentList: the fast tier's Postgres password is generated by the script and reaches the
// API server through a pipe. The server's Secret and courier's DSN hold the same one, in the places the chart's fast-postgres values and
// the Deployment name; no argument of any call holds it; and the Secrets are made with create, which keeps no copy in an annotation.
func TestDeployPostgresNeverPutsThePasswordOnAnArgumentList(t *testing.T) {
	argv, stdin := runDeployPostgres(t, "")

	dsn := regexp.MustCompile(`dsn: "postgres://courier:([0-9a-f]{48})@postgres\.e2e\.svc\.cluster\.local:5432/courier\?sslmode=disable"`).FindStringSubmatch(stdin)
	server := regexp.MustCompile(`password: "([0-9a-f]{48})"`).FindStringSubmatch(stdin)
	if dsn == nil || server == nil || dsn[1] != server[1] {
		t.Fatalf("the manifests piped to kubectl:\n%s\nwant courier-pg's DSN and postgres-auth's password, the same generated one", stdin)
	}
	if !strings.Contains(stdin, "== --context kind-courier-fast create -f -") || strings.Contains(stdin, "last-applied") ||
		!strings.Contains(stdin, "name: courier-pg, namespace: courier") || !strings.Contains(stdin, "name: postgres-auth, namespace: e2e") {
		t.Errorf("the Secrets were not made with create in their namespaces:\n%s", stdin)
	}
	if strings.Contains(argv, dsn[1]) || strings.Contains(argv, "postgres://") || strings.Contains(argv, "--from-literal") {
		t.Errorf("a password or DSN is on an argument list:\n%s", argv)
	}
	if !strings.Contains(argv, "-n e2e rollout status deploy/postgres") {
		t.Errorf("deploy_postgres does not wait for the server:\n%s", argv)
	}
}

// With both Secrets in place the running server's password is kept: nothing is made again and the server is not replaced.
func TestDeployPostgresKeepsTheSecretsItFinds(t *testing.T) {
	argv, stdin := runDeployPostgres(t, "secret/x")
	if strings.Contains(stdin, "kind: Secret") || strings.Contains(argv, "delete") {
		t.Errorf("a re-run with both Secrets present made or deleted something:\n%s\n%s", argv, stdin)
	}
}
